export function calculatePrice(
  baseMonthly: number,
  baseYearly: number,
  cycle: "monthly" | "yearly"
): { billedAmount: number; perMonthEquivalent: number; savingsPercentage: number } {
  if (cycle === "yearly") {
    const totalBilled = Number((baseYearly * 12).toFixed(2));
    const fullMonthlyCost = baseMonthly * 12;
    const savings = Math.round(((fullMonthlyCost - totalBilled) / fullMonthlyCost) * 100);
    return {
      billedAmount: totalBilled,
      perMonthEquivalent: baseYearly,
      savingsPercentage: savings > 0 ? savings : 20,
    };
  }

  return {
    billedAmount: baseMonthly,
    perMonthEquivalent: baseMonthly,
    savingsPercentage: 0,
  };
}
